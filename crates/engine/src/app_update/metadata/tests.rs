use super::*;
use ring::signature::{Ed25519KeyPair, KeyPair};
use serde_json::{Value, json};
use std::{
    io::{self, Cursor},
    time::Duration,
};

fn encoded(bytes: &[u8]) -> String {
    bytes.iter().map(|v| format!("{v:02x}")).collect()
}
fn payload() -> Value {
    json!({"schema":1,"domain":"dlpad.app-update.v1","key_id":"fixture",
        "sequence":2,"version":"0.2.0","channel":"stable",
        "target":"x86_64-pc-windows-msvc","repository":"joongi007/dlpad",
        "asset_name":"dlpad-0.2.0-windows-x86_64-installer.zip",
        "asset_url":"https://github.com/joongi007/dlpad/releases/download/v0.2.0/dlpad-0.2.0-windows-x86_64-installer.zip",
        "asset_bytes":3,"asset_sha256":encoded(&Sha256::digest(b"abc")),
        "issued_at_unix":100,"expires_at_unix":200})
}
fn policy() -> Policy<'static> {
    Policy {
        installed_version: "0.1.0",
        installed_sequence: 1,
        channel: Channel::Stable,
        now_unix: 150,
    }
}
fn check(bytes: &[u8]) -> Result<VerifiedCandidate, Error> {
    // Fixed test-only fixture seed; never an operational signing identity.
    let key = Ed25519KeyPair::from_seed_unchecked(&[7; 32]).unwrap();
    let public: [u8; 32] = key.public_key().as_ref().try_into().unwrap();
    verify_metadata(
        bytes,
        "fixture",
        &encoded(key.sign(bytes).as_ref()),
        &[TrustedKey {
            id: "fixture",
            public_key: &public,
        }],
        &policy(),
    )
}
fn candidate() -> VerifiedCandidate {
    check(&serde_json::to_vec(&payload()).unwrap()).unwrap()
}
fn deadline() -> Instant {
    Instant::now() + Duration::from_secs(10)
}

#[test]
fn valid_signed_metadata_and_exact_package() {
    let c = candidate();
    assert_eq!(c.version(), "0.2.0");
    assert_eq!(c.sequence(), 2);
    assert_eq!(c.channel(), Channel::Stable);
    assert_eq!(c.asset_bytes(), 3);
    assert_eq!(c.expires_at_unix(), 200);
    let p = c
        .verify_package(
            &mut Cursor::new(b"abc"),
            &AtomicBool::new(false),
            deadline(),
        )
        .unwrap();
    assert_eq!(p.bytes(), 3);
    assert_eq!(p.sha256().as_slice(), Sha256::digest(b"abc").as_slice());
}

#[test]
fn persisted_evidence_preserves_exact_signed_bytes_and_rejects_substitution() {
    let bytes = serde_json::to_vec_pretty(&payload()).unwrap();
    let candidate = check(&bytes).unwrap();
    assert_eq!(candidate.signed_payload(), bytes);
    let key = Ed25519KeyPair::from_seed_unchecked(&[7; 32]).unwrap();
    let public: [u8; 32] = key.public_key().as_ref().try_into().unwrap();
    let keys = [TrustedKey {
        id: "fixture",
        public_key: &public,
    }];
    let restored = verify_metadata(
        candidate.signed_payload(),
        candidate.key_id(),
        candidate.signature_hex(),
        &keys,
        &policy(),
    )
    .unwrap();
    assert_eq!(restored.asset_sha256(), candidate.asset_sha256());
    let mut substituted = bytes;
    substituted.push(b'\n');
    assert_eq!(
        verify_metadata(
            &substituted,
            candidate.key_id(),
            candidate.signature_hex(),
            &keys,
            &policy(),
        )
        .unwrap_err(),
        Error::Signature
    );
}

#[test]
fn actual_openssl_signer_fixture_is_verified_by_ring() {
    // Generated by scripts/sign_app_update.py from a synthetic installer ZIP.
    // Only public metadata/signature/key are checked in; no operational key exists.
    let payload = include_bytes!("fixtures/update-windows-x86_64.json");
    let signature = include_str!("fixtures/update-windows-x86_64.json.sig");
    let public = hex::<32>(include_str!("fixtures/public-key.hex").trim()).unwrap();
    let fixture: serde_json::Value = serde_json::from_slice(payload).unwrap();
    let policy = Policy {
        installed_version: "0.0.0",
        installed_sequence: 0,
        channel: Channel::Preview,
        now_unix: fixture["issued_at_unix"].as_u64().unwrap() + 1,
    };
    let keys = [TrustedKey {
        id: "fixture-test-key",
        public_key: &public,
    }];
    let candidate =
        verify_metadata(payload, "fixture-test-key", signature, &keys, &policy).unwrap();
    assert_eq!(candidate.version(), "0.1.0");
    let mut changed = payload.to_vec();
    changed.push(b' ');
    assert_eq!(
        verify_metadata(&changed, "fixture-test-key", signature, &keys, &policy).unwrap_err(),
        Error::Signature
    );
}
#[test]
fn signature_precedes_json_and_rejects_tamper_wrong_key_and_noncanonical_hex() {
    let key = Ed25519KeyPair::from_seed_unchecked(&[7; 32]).unwrap();
    let public: [u8; 32] = key.public_key().as_ref().try_into().unwrap();
    let keys = [TrustedKey {
        id: "fixture",
        public_key: &public,
    }];
    let bytes = serde_json::to_vec(&payload()).unwrap();
    let sig = encoded(key.sign(&bytes).as_ref());
    let mut tampered = bytes.clone();
    tampered.push(b' ');
    for body in [&tampered[..], b"not json"] {
        assert_eq!(
            verify_metadata(body, "fixture", &sig, &keys, &policy()).unwrap_err(),
            Error::Signature
        );
    }
    let wrong: [u8; 32] = Ed25519KeyPair::from_seed_unchecked(&[8; 32])
        .unwrap()
        .public_key()
        .as_ref()
        .try_into()
        .unwrap();
    assert_eq!(
        verify_metadata(
            &bytes,
            "fixture",
            &sig,
            &[TrustedKey {
                id: "fixture",
                public_key: &wrong
            }],
            &policy()
        )
        .unwrap_err(),
        Error::Signature
    );
    for invalid in ["00".to_owned(), sig.to_uppercase(), format!("{sig}00")] {
        assert_eq!(
            verify_metadata(&bytes, "fixture", &invalid, &keys, &policy()).unwrap_err(),
            Error::Signature
        );
    }
    assert_eq!(
        verify_metadata(&bytes, "unregistered", &sig, &keys, &policy()).unwrap_err(),
        Error::UnknownKey
    );
}
#[test]
fn metadata_bounds_and_ambiguous_keyring_fail_closed() {
    assert_eq!(check(&[]).unwrap_err(), Error::MetadataSize);
    assert_eq!(
        check(&vec![b' '; MAX_METADATA_BYTES + 1]).unwrap_err(),
        Error::MetadataSize
    );
    let public = [0u8; 32];
    let bytes = b"{}";
    assert_eq!(
        verify_metadata(bytes, "fixture", "", &[], &policy()).unwrap_err(),
        Error::InvalidKeyring
    );
    assert_eq!(
        verify_metadata(
            bytes,
            "fixture",
            "",
            &[
                TrustedKey {
                    id: "fixture",
                    public_key: &public
                },
                TrustedKey {
                    id: "fixture",
                    public_key: &public
                }
            ],
            &policy()
        )
        .unwrap_err(),
        Error::InvalidKeyring
    );
}
#[test]
fn signed_duplicate_unknown_future_and_invalid_json_are_not_accepted() {
    for text in ["{", r#"{"schema":1,"schema":1}"#] {
        assert_eq!(check(text.as_bytes()).unwrap_err(), Error::Metadata);
    }
    let mut v = payload();
    v["extra"] = json!(true);
    assert_eq!(
        check(&serde_json::to_vec(&v).unwrap()).unwrap_err(),
        Error::Metadata
    );
    v = payload();
    v["schema"] = json!(2);
    assert_eq!(
        check(&serde_json::to_vec(&v).unwrap()).unwrap_err(),
        Error::Policy
    );
}
