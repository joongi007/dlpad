#[test]
fn package_short_long_tamper_and_read_failure_never_verify() {
    let c = candidate();
    let cancel = AtomicBool::new(false);
    for bytes in [&b"ab"[..], &b"abcd"[..]] {
        assert_eq!(
            c.verify_package(&mut Cursor::new(bytes), &cancel, deadline())
                .unwrap_err(),
            Error::PackageSize
        );
    }
    assert_eq!(
        c.verify_package(&mut Cursor::new(b"abd"), &cancel, deadline())
            .unwrap_err(),
        Error::PackageHash
    );
    struct Broken;
    impl Read for Broken {
        fn read(&mut self, _: &mut [u8]) -> io::Result<usize> {
            Err(io::ErrorKind::Other.into())
        }
    }
    assert_eq!(
        c.verify_package(&mut Broken, &cancel, deadline())
            .unwrap_err(),
        Error::PackageRead
    );
    let mut long = Cursor::new(vec![0; 100_000]);
    assert_eq!(
        c.verify_package(&mut long, &cancel, deadline())
            .unwrap_err(),
        Error::PackageSize
    );
    assert_eq!(long.position(), 4, "only one excess byte may be read");
}
#[test]
fn package_cancel_and_deadline_before_and_during_read_never_verify() {
    let c = candidate();
    assert_eq!(
        c.verify_package(&mut Cursor::new(b"abc"), &AtomicBool::new(true), deadline())
            .unwrap_err(),
        Error::Cancelled
    );
    assert_eq!(
        c.verify_package(
            &mut Cursor::new(b"abc"),
            &AtomicBool::new(false),
            Instant::now()
        )
        .unwrap_err(),
        Error::TimedOut
    );
    struct Cancel<'a>(&'a AtomicBool);
    impl Read for Cancel<'_> {
        fn read(&mut self, buf: &mut [u8]) -> io::Result<usize> {
            buf[0] = b'a';
            self.0.store(true, Ordering::Release);
            Ok(1)
        }
    }
    let cancel = AtomicBool::new(false);
    assert_eq!(
        c.verify_package(&mut Cancel(&cancel), &cancel, deadline())
            .unwrap_err(),
        Error::Cancelled
    );
}

#[test]
fn metadata_exact_bound_and_full_duplicate_field_are_checked_after_signature() {
    let mut bytes = serde_json::to_vec(&payload()).unwrap();
    bytes.resize(MAX_METADATA_BYTES, b' ');
    assert!(check(&bytes).is_ok());
    bytes.push(b' ');
    assert_eq!(check(&bytes).unwrap_err(), Error::MetadataSize);
    let valid = serde_json::to_string(&payload()).unwrap();
    let duplicate = valid.replacen("{", "{\"schema\":1,", 1);
    assert_eq!(check(duplicate.as_bytes()).unwrap_err(), Error::Metadata);
}
